def area(a, h): 
    '''
    Вычисление площади триугольника по сторороне и высоте проведённой из противоположной вершины к ней:
    triangle.area(2, 5) -> 5
    '''
    return a * h / 2 

def perimeter(a, b, c): 
    '''Вычисление периметра триугольника по его сторонам: triangle.area(2, 3, 4) -> 9'''
    return a + b + c 
